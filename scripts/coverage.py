"""Builds data/coverage.json from data/coverage.bases.json.

Coverage is every Australian postcode with a locality within radiusKm of a nurse base.
A postcode is metro if any of its localities is Modified Monash Model category 1
(metropolitan); otherwise it is regional. Postcode coordinates come from the
open dataset at github.com/matthewproctor/australianpostcodes.
"""
import csv, io, json, math, pathlib, urllib.request
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = 'https://raw.githubusercontent.com/matthewproctor/australianpostcodes/master/australian_postcodes.csv'
cfg = json.loads((ROOT / 'data/coverage.bases.json').read_text())
R = cfg['radiusKm']

text = urllib.request.urlopen(SRC, timeout=60).read().decode('utf-8')
rows = [r for r in csv.DictReader(io.StringIO(text)) if r['type'] in ('Delivery Area', '') and r['lat'] and r['long']]
bypc = defaultdict(list)
for r in rows:
    bypc[r['postcode']].append(r)

def point(name, pc):
    m = [r for r in bypc[pc] if r['locality'] == name.upper()] or bypc[pc]
    if not m:
        raise SystemExit(f'Unknown postcode for base {name} {pc}')
    return sum(float(r['lat']) for r in m) / len(m), sum(float(r['long']) for r in m) / len(m)

def km(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (*a, *b))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 12742 * math.asin(math.sqrt(h))

import re
bases = [(point(n, pc), area) for n, pc, area in cfg['bases']]
metro, regional = set(), set()
areas = {slug: {'slug': slug, 'name': nm, 'state': st, 'metro': [], 'regional': [], 'suburbs': []} for slug, (nm, st) in cfg['areas'].items()}
SKIP = re.compile(r'\b(DC|MC|BC|LPO|PO|MAIL CENTRE|DELIVERY CENTRE|BUSINESS CENTRE)\b')
for pc, rs in bypc.items():
    dist = [(km((float(r['lat']), float(r['long'])), b), area) for r in rs for b, area in bases]
    near = min(dist)
    if near[0] <= R:
        kind = 'metro' if any(r['MMM_2019'] == '1' for r in rs) else 'regional'
        (metro if kind == 'metro' else regional).add(pc)
        a = areas[near[1]]
        a[kind].append(pc)
        for r in rs:
            within = min(km((float(r['lat']), float(r['long'])), b) for b, _ in bases) <= R
            if within and r['type'] == 'Delivery Area' and not SKIP.search(r['locality']):
                a['suburbs'].append([r['locality'].title().replace("'S", "'s"), pc])
for a in areas.values():
    a['metro'].sort(); a['regional'].sort()
    a['suburbs'] = sorted({tuple(x) for x in a['suburbs']}, key=lambda x: x[0])
(ROOT / 'data/areas.json').write_text(json.dumps({'_readme': 'Generated by scripts/coverage.py. Public area pages; do not edit by hand.', 'areas': list(areas.values())}, indent=1) + '\n')

out = {'_readme': 'Generated by scripts/coverage.py from data/coverage.bases.json. Do not edit by hand.',
       'metro': sorted(metro), 'regional': sorted(regional)}
(ROOT / 'data/coverage.json').write_text(json.dumps(out, indent=1) + '\n')
print(f'{len(metro)} metro and {len(regional)} regional postcodes within {R} km of {len(bases)} bases')
