"""Builds data/postcode-class.json: every Australian postcode with a metropolitan locality
(Modified Monash Model category 1). Used to price home visits outside the listed coverage
area, so payment is always taken online. Source: github.com/matthewproctor/australianpostcodes."""
import csv, io, json, pathlib, urllib.request
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = 'https://raw.githubusercontent.com/matthewproctor/australianpostcodes/master/australian_postcodes.csv'
text = urllib.request.urlopen(SRC, timeout=60).read().decode('utf-8')
metro = sorted({r['postcode'] for r in csv.DictReader(io.StringIO(text)) if r['MMM_2019'] == '1' and len(r['postcode']) == 4})
(ROOT / 'data/postcode-class.json').write_text(json.dumps({'_readme': 'Generated by scripts/postcode-class.py. Metro postcodes nationally; all others are priced as regional.', 'metro': metro}) + '\n')
print(len(metro), 'metro postcodes')
