"""Builds data/postcode-class.json: metropolitan postcodes (Modified Monash Model category 1)
within outerKm of a nurse base. Home visits outside the listed coverage area are priced metro
if listed here and regional otherwise, so anything beyond outerKm is always the regional fee.
Payment is always taken online. Source: github.com/matthewproctor/australianpostcodes."""
import csv, io, json, math, pathlib, urllib.request
from collections import defaultdict
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = 'https://raw.githubusercontent.com/matthewproctor/australianpostcodes/master/australian_postcodes.csv'
OUTER_KM = 40
cfg = json.loads((ROOT / 'data/coverage.bases.json').read_text())
text = urllib.request.urlopen(SRC, timeout=60).read().decode('utf-8')
rows = [r for r in csv.DictReader(io.StringIO(text)) if r['type'] in ('Delivery Area', '') and r['lat'] and r['long']]
bypc = defaultdict(list)
for r in rows: bypc[r['postcode']].append(r)
def point(name, pc):
    m = [r for r in bypc[pc] if r['locality'] == name.upper()] or bypc[pc]
    return sum(float(r['lat']) for r in m) / len(m), sum(float(r['long']) for r in m) / len(m)
def km(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (*a, *b))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 12742 * math.asin(math.sqrt(h))
bases = [point(n, pc) for n, pc, _ in cfg['bases']]
metro = sorted(pc for pc, rs in bypc.items() if len(pc) == 4 and any(r['MMM_2019'] == '1' for r in rs)
               and min(km((float(r['lat']), float(r['long'])), b) for r in rs for b in bases) <= OUTER_KM)
(ROOT / 'data/postcode-class.json').write_text(json.dumps({'_readme': f'Generated by scripts/postcode-class.py. Metro postcodes within {OUTER_KM} km of a nurse base; any other postcode outside the listed area is charged the regional fee.', 'outerKm': OUTER_KM, 'metro': metro}) + '\n')
print(len(metro), f'metro postcodes within {OUTER_KM} km')
